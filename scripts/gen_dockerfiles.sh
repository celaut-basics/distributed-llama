#!/bin/sh
# Make <role>/<arch>/.service/Dockerfile = llama/build-stage.Dockerfile + <role>/runtime.Dockerfile.
# The packer needs a real Dockerfile in each pack root. The build stage is the same text in
# the head and the worker, so BuildKit builds llama.cpp once for both.
# tests/test_layout.py checks that the files are up to date.
set -eu
cd "$(dirname "$0")/.."
for role in head worker; do
  for arch in amd64; do
    out="$role/$arch/.service/Dockerfile"
    {
      echo "# GENERATED by scripts/gen_dockerfiles.sh from llama/build-stage.Dockerfile and"
      echo "# $role/runtime.Dockerfile. Edit those files, not this one. linux/$arch variant."
      cat llama/build-stage.Dockerfile "$role/runtime.Dockerfile"
    } > "$out"
  done
done
