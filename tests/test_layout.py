"""The pack roots: generated Dockerfiles up to date, one llama.cpp build stage for both
images, the links of the roots, and the manifests."""

import json
import os
import subprocess

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def read(*path):
    with open(os.path.join(ROOT, *path)) as fh:
        return fh.read()


def test_dockerfiles_are_generated():
    for role in ("head", "worker"):
        expected = ("# GENERATED by scripts/gen_dockerfiles.sh from llama/build-stage.Dockerfile and\n"
                    "# %s/runtime.Dockerfile. Edit those files, not this one. linux/amd64 variant.\n"
                    % role) + read("llama", "build-stage.Dockerfile") + read(role, "runtime.Dockerfile")
        assert read(role, "amd64", ".service", "Dockerfile") == expected, \
            "run scripts/gen_dockerfiles.sh"


def test_links_of_the_pack_roots():
    assert os.readlink(os.path.join(ROOT, "head", "amd64", "app")) == "../app"
    assert os.readlink(os.path.join(ROOT, "head", "amd64", "worker")) == "../../worker/amd64"


def test_manifests():
    head = json.loads(read("head", "amd64", ".service", "service.json"))
    worker = json.loads(read("worker", "amd64", ".service", "service.json"))
    stack = head["api"][0]["protocol_stack"]
    assert stack[0] == ["http2"] and stack[1] == ["grpc"] and stack[2]["tags"] == ["chat"]
    assert head["api"][0]["port"] == 8080 and worker["api"][0]["port"] == 50052
    for svc in (head, worker):
        assert svc["architecture"] == "linux/amd64"
        assert "network" not in svc  # no egress: the model is in the image
        r = svc["resources"]
        assert r["at_init"] == r["at_most"] and r["at_init"]["cpu_quota"] == 400000
    pack = json.loads(read("head", "amd64", ".service", "pack_config.json"))
    assert pack["dependencies"] == {"WORKER": "worker"} and pack["dependencies_env"]


def test_ports_match_the_code():
    from_code = read("head", "app", "cluster.py")
    assert "WORKER_PORT = 50052" in from_code
    assert "-p 50052" in read("worker", "runtime.Dockerfile")
